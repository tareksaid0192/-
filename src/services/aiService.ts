export async function getSpecialistAIResponse(userMessage: string): Promise<string> {
  // Simulate natural delay for realistic chat experience
  await new Promise((resolve) => setTimeout(resolve, 800));

  const lower = userMessage.toLowerCase();
  for (const [kw, key] of Object.entries(KEYWORDS)) {
    if (lower.includes(kw)) {
      return ABA_RESPONSES[key];
    }
  }

  return ABA_RESPONSES.default;
}
